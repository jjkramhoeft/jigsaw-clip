# Lists the video files in the videos folder and writes videos/library.js,
# which the game reads (browsers can't list a folder when opened from disk).
$ErrorActionPreference = 'Stop'
$videos = Join-Path $PSScriptRoot '..\videos'
New-Item -ItemType Directory -Force $videos | Out-Null

$exts = '.mp4', '.webm', '.m4v', '.mov', '.ogv'
$items = @(Get-ChildItem -LiteralPath $videos -File |
  Where-Object { $exts -contains $_.Extension.ToLower() } |
  Sort-Object Name |
  ForEach-Object { [pscustomobject]@{ file = $_.Name; title = $_.BaseName -replace '[_-]+', ' ' } })

$json = if ($items.Count) { ConvertTo-Json -InputObject $items -Compress } else { '[]' }
$js = "// Generated by tools/scan-videos.ps1. Run it again after adding videos.`nwindow.VIDEO_LIBRARY = $json;`n"
[IO.File]::WriteAllText((Join-Path $videos 'library.js'), $js, (New-Object Text.UTF8Encoding $false))
Write-Host "Found $($items.Count) video(s) in videos\"
